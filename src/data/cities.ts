// Search cities by name
export function searchCities(query: string, limit: number = 10): City[] {
  if (!query || query.length < 2) return [];
  
  const lowerQuery = query.toLowerCase();
  
  return CITIES
    .filter(city => {
      const searchStr = `${city.name} ${city.state || ''} ${city.country}`.toLowerCase();
      return searchStr.includes(lowerQuery);
    })
    .slice(0, limit);
}

// Format city for display
export function formatCityDisplay(city: City): string {
  if (city.state) {
    return `${city.name}, ${city.state}, ${city.country}`;
  }
  return `${city.name}, ${city.country}`;
}
